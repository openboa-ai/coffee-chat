import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const __dirname = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(__dirname, "..");
const distDir = resolve(pkgRoot, "dist");
const require = createRequire(import.meta.url);

mkdirSync(distDir, { recursive: true });

// Bundle Yogurt CSS + Coffee Chat UI CSS inline (with data URL fonts so CSP stays strict!).
const yogurtCssPath = require.resolve("@openboa/yogurt/styles.css");
const uiCssPath = resolve(pkgRoot, "../ui/src/styles.css");

const cssBuild = await esbuild.build({
  stdin: {
    contents: `@import ${JSON.stringify(yogurtCssPath)};\n@import ${JSON.stringify(uiCssPath)};\n`,
    resolveDir: pkgRoot,
    loader: "css",
  },
  bundle: true,
  minify: true,
  write: false,
  loader: {
    ".woff2": "dataurl",
    ".woff": "dataurl",
    ".ttf": "dataurl",
    ".svg": "dataurl",
  },
});

const inlinedCss = cssBuild.outputFiles[0]!.text;

const apps = [
  {
    name: "confirm-bean",
    title: "Coffee Chat — Confirm Bean",
    entry: resolve(pkgRoot, "src/confirm-bean.tsx"),
    constName: "CONFIRM_BEAN_HTML",
  },
  {
    name: "bean-picker",
    title: "Coffee Chat — Bean Picker",
    entry: resolve(pkgRoot, "src/bean-picker.tsx"),
    constName: "BEAN_PICKER_HTML",
  },
  {
    name: "perspective-diff",
    title: "Coffee Chat — Perspective Diff",
    entry: resolve(pkgRoot, "src/perspective-diff.tsx"),
    constName: "PERSPECTIVE_DIFF_HTML",
  },
] as const;

const generatedExports: string[] = [
  "// Auto-generated by scripts/build.ts — do not edit directly.",
];

for (const app of apps) {
  const jsBuild = await esbuild.build({
    entryPoints: [app.entry],
    bundle: true,
    minify: true,
    format: "iife",
    target: ["es2022"],
    jsx: "automatic",
    write: false,
    define: {
      "process.env.NODE_ENV": '"production"',
    },
  });

  const jsCode = jsBuild.outputFiles[0]!.text.replaceAll(
    "</script>",
    "<\\/script>",
  );
  const safeCss = inlinedCss.replaceAll("</style>", "<\\/style>");

  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>${app.title}</title>
<style>${safeCss}</style>
</head>
<body style="margin:0">
<div id="root"></div>
<script>${jsCode}</script>
</body>
</html>`;

  const outHtmlPath = resolve(distDir, `${app.name}.html`);
  writeFileSync(outHtmlPath, html, "utf8");

  const sizeBytes = Buffer.byteLength(html, "utf8");
  if (sizeBytes > 10 * 1024 * 1024) {
    throw new Error(`MCP App ${app.name} exceeds 10 MiB limit (${sizeBytes} bytes)`);
  }

  generatedExports.push(`export const ${app.constName} = ${JSON.stringify(html)};`);
  console.log(`Built ${app.name}.html (${Math.round(sizeBytes / 1024)} KiB)`);
}

writeFileSync(
  resolve(pkgRoot, "src/generated.ts"),
  generatedExports.join("\n") + "\n",
  "utf8",
);

// Sanity readback
readFileSync(resolve(distDir, "confirm-bean.html"), "utf8");
